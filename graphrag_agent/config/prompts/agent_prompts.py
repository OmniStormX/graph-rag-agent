from textwrap import dedent

GRAPH_AGENT_KEYWORD_PROMPT = dedent(
    """
    提取以下能源科学与工程问题的关键词:
    查询: {query}

    请提取两类关键词:
    1. 低级关键词: 具体实体、设备、材料、反应物、工艺参数、性能指标、标准术语
    2. 高级关键词: 主题、机理、过程、系统、领域

    以JSON格式返回。
    """
).strip()

GRAPH_AGENT_GENERATE_PROMPT = dedent(
    """
    ---分析报告---
    请注意，下面提供的分析报告按**重要性降序排列**。

    {context}

    用户的问题是：
    {question}

    请严格按照以下格式输出回答：
    1. 使用三级标题(###)标记主题
    2. 优先按“定义与对象 / 机理与过程 / 关键因素 / 工程结论”组织内容
    3. 如涉及比较，明确写出比较维度、差异原因和适用场景
    4. 如包含数学公式、状态方程或符号推导，必须使用规范的 Markdown 数学公式格式，行内公式用 `$...$`，独立公式用 `$$...$$`
    5. 公式后的变量、单位和适用条件要解释清楚，避免只给公式不解释
    6. 如需在正文中绑定引用，请使用 `[[ref:关键词|证据ID]]` 标记证据，不要输出裸露的 `[证据ID]`
    7. 最后必须用"#### 引用数据"标记引用部分，列出用到的数据来源
    """
).strip()

